"""Partial ordering over ``TrainingEvent``s.

The rule this module exists to enforce (Phase 1 brief section 2.2):

    It is forbidden to claim cross-rank absolute temporal order from
    ``(run_id, rank, step, microstep, seq)``.

Four distinct concepts are therefore kept apart and must never be conflated:

=====================  ==========================  ==============================
Concept                Fields                      What it can establish
=====================  ==========================  ==============================
logical position       ``step``, ``microstep``     which training step an event
                                                   describes -- *not* who ran first
producer-local order   ``rank``, ``source_seq``    a total order *within one
                                                   emitting stream*; nothing across
observation time       ``wall_time_ns``,           when we observed it; never a
                       ``monotonic_time_ns``       happens-before witness
storage order          ``ingest_seq``              physical append order; never
                                                   causal
=====================  ==========================  ==============================

A ``BEFORE`` claim is returned **only** with a witness:

``producer_sequence``
    Both events come from the same producer and ``source_seq`` orders them.
    A single producer emits sequentially, so this is a genuine happens-before.
``causal_edge``
    ``b.parent_event_id == a.event_id``. An explicit causal link is a
    happens-before by construction.
``barrier``
    A caller-supplied barrier witness (e.g. a collective that every rank
    participated in). Phase 1 has no producer of such evidence, so this witness
    is accepted but never fabricated.

Everything else -- including ``step`` comparison across producers -- yields
``CONCURRENT_OR_UNKNOWN``. The logical-step relation is still *reported*, as a
hint on the result, clearly separated from the ordering claim, because the
incident engine legitimately wants to say "the gradient metric described step
810 while the loss described step 812" without asserting which ran first.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

from .enums import OrderingConfidence, OrderingRelation
from .event import TrainingEvent

__all__ = [
    "OrderingResult",
    "EarliestEvidence",
    "EventOrdering",
    "BARRIER_WITNESS",
]

#: Recognised values of ``OrderingContext.barrier_witness``. A caller that can
#: prove a step barrier passes one of these; Phase 1 never does.
BARRIER_WITNESS = frozenset({"step_barrier", "collective_barrier"})


@dataclass
class OrderingResult:
    """Outcome of comparing two events.

    ``relation`` is the claim. ``evidence`` explains it, and ``is_proven`` is
    true only when a witness backs it. ``hints`` carries *non-authoritative*
    context (the logical-step relation and the wall-clock delta) that callers
    may report but must not treat as ordering.
    """

    relation: OrderingRelation
    confidence: OrderingConfidence
    evidence: str
    is_proven: bool
    hints: Dict[str, Any] = field(default_factory=dict)

    @property
    def is_gap(self) -> bool:
        """True when this comparison failed for lack of data, not by proof.

        The distinction matters for :meth:`EventOrdering.earliest`: abstaining
        *because we proved there is no witness* still lets us compute the exact
        minimal set, whereas abstaining because a field is missing does not.
        """
        return not self.is_proven and self.confidence in (
            OrderingConfidence.LOW,
            OrderingConfidence.UNKNOWN,
        )

    def __str__(self) -> str:  # pragma: no cover - diagnostics only
        return "{}({})".format(self.relation, self.evidence)


@dataclass
class EarliestEvidence:
    """The set of minimal elements among a group of abnormal events.

    Implements the three cases required by Phase 1 brief section 8.4:

    * Case 1 -- exactly one minimal element: ``first_abnormal_event_id`` is set.
    * Case 2 -- several proven-incomparable minima: the id is ``None`` and
      ``ordering_confidence`` is ``PROVEN`` (we *proved* they are concurrent).
    * Case 3 -- ordering could not be established: the id is ``None`` and
      ``ordering_confidence`` is ``UNKNOWN`` or ``LOW``.

    ``explanation`` is a deterministic, human-readable sentence built from the
    data. It is never generated by a language model.
    """

    candidates: List[TrainingEvent]
    ordering_confidence: OrderingConfidence
    first_abnormal_event_id: Optional[str]
    explanation: str
    comparable_pairs: int = 0
    unprovable_pairs: int = 0
    hints: Dict[str, Any] = field(default_factory=dict)

    @property
    def is_unique(self) -> bool:
        return self.first_abnormal_event_id is not None

    def candidate_ids(self) -> List[str]:
        return [c.event_id for c in self.candidates]


class EventOrdering:
    """Stateless partial-order algebra over events.

    All methods are pure; nothing here mutates an event or holds global state.
    """

    # -- primitive comparison -------------------------------------------------

    @staticmethod
    def compare(
        a: TrainingEvent,
        b: TrainingEvent,
        *,
        barrier_witness: Optional[str] = None,
    ) -> OrderingResult:
        """Compare two events, returning the *weakest defensible* relation."""
        if a.event_id == b.event_id:
            return OrderingResult(
                OrderingRelation.SAME_POSITION,
                OrderingConfidence.PROVEN,
                "same_event_id",
                True,
            )

        if a.run_id != b.run_id:
            return OrderingResult(
                OrderingRelation.CONCURRENT_OR_UNKNOWN,
                OrderingConfidence.UNKNOWN,
                "different_run",
                False,
            )

        # Witness 1: explicit causal edge. Checked before producer identity
        # because a causal edge is authoritative even across producers.
        if b.parent_event_id and b.parent_event_id == a.event_id:
            return OrderingResult(
                OrderingRelation.BEFORE,
                OrderingConfidence.PROVEN,
                "causal_edge",
                True,
            )
        if a.parent_event_id and a.parent_event_id == b.event_id:
            return OrderingResult(
                OrderingRelation.AFTER,
                OrderingConfidence.PROVEN,
                "causal_edge",
                True,
            )

        hints = EventOrdering._hints(a, b)

        # Witness 2: same producer, ordered by source_seq.
        if a.producer_id == b.producer_id:
            if a.source_seq is not None and b.source_seq is not None:
                seq_relation = (
                    OrderingRelation.BEFORE
                    if a.source_seq < b.source_seq
                    else OrderingRelation.AFTER
                    if a.source_seq > b.source_seq
                    else OrderingRelation.SAME_POSITION
                )
                if seq_relation is OrderingRelation.SAME_POSITION:
                    # Equal sequence within one producer: a producer bug,
                    # reported rather than silently tolerated. Not an ordering.
                    hints = dict(hints)
                    hints["duplicate_source_seq"] = True
                    return OrderingResult(
                        OrderingRelation.SAME_POSITION,
                        OrderingConfidence.LOW,
                        "duplicate_producer_sequence",
                        False,
                        hints,
                    )

                # Conflict guard. ``source_seq`` records *emission* order, which
                # equals *training* order only if the producer emits each step's
                # observations in training order. A producer that defers or
                # batches (e.g. flushing layer metrics on a different cadence)
                # can emit step 812's loss before step 810's gradient metric.
                # When the sequence and the declared logical positions disagree,
                # we cannot claim training order, so we abstain loudly instead of
                # building a false "X preceded Y" story on emission order.
                pa, pb = a.logical_position, b.logical_position
                if pa is not None and pb is not None and pa != pb:
                    position_says = (
                        OrderingRelation.BEFORE if pa < pb else OrderingRelation.AFTER
                    )
                    if position_says is not seq_relation:
                        conflict_hints = dict(hints)
                        conflict_hints["sequence_position_conflict"] = True
                        conflict_hints["emission_order_relation"] = str(seq_relation)
                        return OrderingResult(
                            OrderingRelation.CONCURRENT_OR_UNKNOWN,
                            OrderingConfidence.LOW,
                            "producer_sequence_position_conflict",
                            False,
                            conflict_hints,
                        )

                return OrderingResult(seq_relation, OrderingConfidence.PROVEN, "producer_sequence", True, hints)
            return OrderingResult(
                OrderingRelation.CONCURRENT_OR_UNKNOWN,
                OrderingConfidence.UNKNOWN,
                "same_producer_without_source_seq",
                False,
                hints,
            )

        # Witness 3: caller-supplied barrier. Never fabricated here.
        if barrier_witness in BARRIER_WITNESS and a.logical_position is not None and b.logical_position is not None:
            if a.logical_position < b.logical_position:
                return OrderingResult(OrderingRelation.BEFORE, OrderingConfidence.HIGH, barrier_witness, True, hints)
            if a.logical_position > b.logical_position:
                return OrderingResult(OrderingRelation.AFTER, OrderingConfidence.HIGH, barrier_witness, True, hints)

        # Different producers: no witness exists in the data.
        if a.logical_position is not None and b.logical_position is not None:
            if a.logical_position == b.logical_position:
                # Same training position: provably the same position, and
                # provably not ordered relative to one another.
                return OrderingResult(
                    OrderingRelation.SAME_POSITION,
                    OrderingConfidence.PROVEN,
                    "same_logical_position_different_producers",
                    False,
                    hints,
                )
            # Different positions but different producers: the *step* relation is
            # known, the *happens-before* relation is not. This is deliberately
            # classified as a knowledge GAP (confidence UNKNOWN) rather than as
            # proven concurrency: two ranks at steps 810 and 812 are almost
            # certainly ordered in reality, we simply cannot prove which way, so
            # the honest output is "ordering cannot be established" rather than
            # "these are concurrent".
            return OrderingResult(
                OrderingRelation.CONCURRENT_OR_UNKNOWN,
                OrderingConfidence.UNKNOWN,
                "cross_producer_step_relation_not_provable",
                False,
                hints,
            )

        return OrderingResult(
            OrderingRelation.CONCURRENT_OR_UNKNOWN,
            OrderingConfidence.UNKNOWN,
            "no_logical_position",
            False,
            hints,
        )

    @staticmethod
    def _hints(a: TrainingEvent, b: TrainingEvent) -> Dict[str, Any]:
        """Non-authoritative context. Reported, never used to order."""
        hints: Dict[str, Any] = {}
        pa, pb = a.logical_position, b.logical_position
        if pa is not None and pb is not None:
            if pa < pb:
                hints["logical_step_hint"] = "a_lower"
            elif pa > pb:
                hints["logical_step_hint"] = "b_lower"
            else:
                hints["logical_step_hint"] = "equal"
        hints["wall_delta_ns"] = b.wall_time_ns - a.wall_time_ns
        hints["rank_a"] = a.rank
        hints["rank_b"] = b.rank
        return hints

    @staticmethod
    def happens_before(
        a: TrainingEvent, b: TrainingEvent, *, barrier_witness: Optional[str] = None
    ) -> bool:
        """True only when ``a`` provably happens before ``b``.

        The conservative predicate: anything unproven returns ``False``. Callers
        that need to distinguish "proven not-before" from "unknown" must use
        :meth:`compare`.
        """
        result = EventOrdering.compare(a, b, barrier_witness=barrier_witness)
        return result.relation is OrderingRelation.BEFORE and result.is_proven

    # -- minimal elements -----------------------------------------------------

    @staticmethod
    def earliest(
        events: Sequence[TrainingEvent],
        *,
        barrier_witness: Optional[str] = None,
        max_pairwise: int = 4000,
    ) -> EarliestEvidence:
        """Return the minimal elements of the partial order over ``events``.

        The earliest abnormal evidence is, by definition, the set of events
        that no other event in the set provably precedes. That definition is
        what makes this correct in the multi-rank case: when two ranks each
        report an anomaly at the same logical step and neither provably
        precedes the other, the honest answer is *both*, not a coin flip.

        Raises ``ValueError`` if ``len(events)`` exceeds ``max_pairwise``:
        the candidate set is meant to be small, and silently doing an O(n^2)
        scan over thousands of events would be a performance bug rather than a
        correctness win.
        """
        events = list(events)
        if not events:
            return EarliestEvidence(
                candidates=[],
                ordering_confidence=OrderingConfidence.UNKNOWN,
                first_abnormal_event_id=None,
                explanation="No abnormal events were supplied, so no earliest abnormal event exists.",
            )
        if len(events) > max_pairwise:
            raise ValueError(
                "earliest() received %d events (limit %d); narrow the candidate set first"
                % (len(events), max_pairwise)
            )
        if len(events) == 1:
            only = events[0]
            return EarliestEvidence(
                candidates=[only],
                ordering_confidence=OrderingConfidence.PROVEN,
                first_abnormal_event_id=only.event_id,
                explanation=(
                    "Exactly one abnormal event is in scope, so it is trivially the "
                    "earliest defensible abnormal event."
                ),
                comparable_pairs=0,
                unprovable_pairs=0,
            )

        minima: List[TrainingEvent] = []
        comparable_pairs = 0
        unprovable_pairs = 0
        gaps = 0

        # Full pairwise pass. The candidate set is small by contract
        # (``max_pairwise`` guards it), and an exact count of gaps is what makes
        # ``ordering_confidence`` meaningful rather than decorative.
        precedes: Dict[str, List[str]] = {e.event_id: [] for e in events}
        for i, other in enumerate(events):
            for candidate in events[i + 1 :]:
                forward = EventOrdering.compare(other, candidate, barrier_witness=barrier_witness)
                if forward.relation is OrderingRelation.BEFORE and forward.is_proven:
                    precedes[candidate.event_id].append(other.event_id)
                    comparable_pairs += 1
                elif forward.relation is OrderingRelation.AFTER and forward.is_proven:
                    precedes[other.event_id].append(candidate.event_id)
                    comparable_pairs += 1
                else:
                    if forward.is_gap:
                        gaps += 1
                        unprovable_pairs += 1
                    else:
                        # Abstention backed by proof (same position, or no
                        # witness can exist). Not a gap in our knowledge.
                        comparable_pairs += 1

        for candidate in events:
            if not precedes[candidate.event_id]:
                minima.append(candidate)

        # Deterministic output order that is explicitly *not* a causal claim.
        minima.sort(key=EventOrdering.storage_sort_key)

        if len(minima) == 1:
            winner = minima[0]
            if gaps == 0:
                confidence = OrderingConfidence.PROVEN
                explanation = (
                    "Unique earliest abnormal event: {metric} on {where}. "
                    "Every other abnormal event in scope is provably preceded by it.".format(
                        metric=winner.metric_name or winner.event_type,
                        where=EventOrdering.describe_origin(winner),
                    )
                )
            else:
                # A gap could hide a predecessor we cannot see, so the unique
                # minimum is the best available candidate but is not proven.
                confidence = OrderingConfidence.LOW
                explanation = (
                    "Best available earliest abnormal event: {metric} on {where}. "
                    "It is the only event in scope that no other event provably precedes, but "
                    "{gaps} comparison(s) could not be settled from the available evidence, so "
                    "an earlier event cannot be ruled out.".format(
                        metric=winner.metric_name or winner.event_type,
                        where=EventOrdering.describe_origin(winner),
                        gaps=gaps,
                    )
                )
        else:
            confidence = (
                OrderingConfidence.PROVEN if gaps == 0 else OrderingConfidence.UNKNOWN
            )
            lines = [
                "{n} abnormal events are mutually unordered, so no single event can be "
                "named first:".format(n=len(minima))
            ]
            for m in minima:
                lines.append(
                    "  - {metric} = {value} on {where}, step {step}".format(
                        metric=m.metric_name or m.event_type,
                        value=m.metric_value,
                        where=EventOrdering.describe_origin(m),
                        step=m.step,
                    )
                )
            if gaps == 0:
                lines.append(
                    "They are provably concurrent: no happens-before witness links them."
                )
            else:
                lines.append(
                    "Their exact ordering cannot be established from the available evidence."
                )
            explanation = "\n".join(lines)

        return EarliestEvidence(
            candidates=minima,
            ordering_confidence=confidence,
            first_abnormal_event_id=minima[0].event_id if len(minima) == 1 and gaps == 0 else None,
            explanation=explanation,
            comparable_pairs=comparable_pairs,
            unprovable_pairs=unprovable_pairs,
            hints={"gaps": gaps, "minima": len(minima)},
        )

    # -- deterministic, explicitly non-causal presentation order --------------

    @staticmethod
    def storage_sort_key(event: TrainingEvent) -> Tuple:
        """Deterministic presentation key.

        Not a causal order. It exists so that CLI output and golden files are
        byte-stable across runs, which is required for the regression corpus in
        ``tests/scenarios``. The name says ``storage`` and not ``causal`` on
        purpose.
        """
        pos = event.logical_position
        return (
            pos[0] if pos else -1,
            pos[1] if pos else -1,
            event.producer_id,
            event.source_seq if event.source_seq is not None else -1,
            event.ingest_seq if event.ingest_seq is not None else -1,
            event.event_id,
        )

    @staticmethod
    def sort_deterministic(events: Iterable[TrainingEvent]) -> List[TrainingEvent]:
        return sorted(events, key=EventOrdering.storage_sort_key)

    @staticmethod
    def describe_origin(event: TrainingEvent) -> str:
        """Human-readable provenance with rank only when rank is known."""
        bits = [event.source or "unknown-source"]
        if event.rank is not None:
            bits.append("rank {}".format(event.rank))
        if event.module_path:
            bits.append(event.module_path)
        elif event.layer_index is not None:
            bits.append("layer {}".format(event.layer_index))
        return " ".join(bits)
